#  Base Test Case
# ---------------------------------------------------------------------------


class NceStudioTestCase(FrappeTestCase):
    """Base class for all NCE Studio tests.

    Extends ``FrappeTestCase`` with app-specific setup/teardown and helpers.
    Subclass this instead of ``FrappeTestCase`` directly so that shared
    fixtures or flags only need to be declared in one place.

    Example::

        class TestNceDoctype(NceStudioTestCase):
            def test_creation(self):
                doc = make_nce_doctype(title="Hello")
                self.assertEqual(doc.title, "Hello")
                self.assertEqual(doc.status, "Open")
    """

    @classmethod
    def setUpClass(cls):
        super().setUpClass()
        # Any one-time setup for the entire test class goes here.
        # e.g. create a test user, enable a feature flag, etc.

    @classmethod
    def tearDownClass(cls):
        super().tearDownClass()
        # Any one-time cleanup for the entire test class goes here.

    def setUp(self):
        super().setUp()
        # Runs before each individual test method.

    def tearDown(self):
        super().tearDown()
        # Runs after each individual test method.
        frappe.db.rollback()

    # ------------------------------------------------------------------
    #  Convenience assertions
    # ------------------------------------------------------------------

    def assertDocExists(self, doctype, name, msg=None):
        """Assert that a document with the given name exists."""
        self.assertTrue(
            frappe.db.exists(doctype, name),
            msg or f"{doctype} '{name}' should exist but was not found.",
        )

    def assertDocNotExists(self, doctype, name, msg=None):
        """Assert that a document with the given name does NOT exist."""
        self.assertFalse(
            frappe.db.exists(doctype, name),
            msg or f"{doctype} '{name}' should not exist but was found.",
        )

    def assertDocValue(self, doctype, name, fieldname, expected, msg=None):
        """Assert that a document field has the expected value in the DB."""
        actual = frappe.db.get_value(doctype, name, fieldname)
        self.assertEqual(
            actual,
            expected,
            msg
            or f"{doctype} '{name}'.{fieldname}: expected {expected!r}, got {actual!r}",
        )

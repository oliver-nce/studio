from __future__ import unicode_literals

import frappe
from frappe.tests.utils import FrappeTestCase

# ---------------------------------------------------------------------------
#  Helpers — version detection
# ---------------------------------------------------------------------------


def get_frappe_major_version():
    """Return the major version of the installed Frappe framework as an int.

    Centralised here so tests can branch on version when absolutely necessary.
    """
    return int(frappe.__version__.split(".")[0])


def is_v16_or_later():
    """True when running on Frappe v16+."""
    return get_frappe_major_version() >= 16


# ---------------------------------------------------------------------------
#  Helpers — test data factories
# ---------------------------------------------------------------------------


def make_nce_doctype(**kwargs):
    """Create and insert a NCE Doctype document for testing.

    Pass any field as a keyword argument to override the defaults.

    Returns:
        frappe.Document: The newly inserted document.

    Example::

        doc = make_nce_doctype(title="Test Record", status="In Progress")
        assert doc.name
    """
    defaults = {
        "doctype": "NCE Doctype",
        "title": "Test Record",
        "status": "Open",
        "description": "Auto-generated by test suite.",
    }
    defaults.update(kwargs)

    doc = frappe.get_doc(defaults)
    doc.insert(ignore_permissions=True)
    return doc


def cleanup_test_records(doctype="NCE Doctype", filters=None):
    """Delete all test records matching *filters* (or all records of the DocType).

    Useful in ``tearDown`` / ``tearDownClass`` to leave the DB clean.

    Args:
        doctype (str): DocType name to clean up.
        filters (dict | None): Optional Frappe-style filters. If ``None``,
            deletes **all** records of the given DocType — use with care.
    """
    records = frappe.get_all(doctype, filters=filters, pluck="name")
    for name in records:
        frappe.delete_doc(doctype, name, force=True, ignore_permissions=True)
    frappe.db.commit()


